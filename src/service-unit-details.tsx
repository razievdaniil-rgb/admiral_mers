export function ServiceUnitDetails({ service }: { service: string }) {
  if (!units[service]) return null;
  return (
    <section className="container section">
      <div className="price-section-heading">
        <div>
          <p className="eyebrow">Подробнее по узлам</p>
          <h2>
            {service === "transmission"
              ? "От коробки до привода"
              : "Электрика: питание, проводка и системы автомобиля"}
          </h2>
        </div>
      </div>
      <div className="service-unit-grid">
        {units[service].map((unit) => (
          <article key={unit.title}>
            <h3>{unit.title}</h3>
            <p>{unit.description}</p>
            <ul>
              {unit.works.map((work) => (
                <li key={work}>{work}</li>
              ))}
            </ul>
          </article>
        ))}
      </div>
    </section>
  );
}
